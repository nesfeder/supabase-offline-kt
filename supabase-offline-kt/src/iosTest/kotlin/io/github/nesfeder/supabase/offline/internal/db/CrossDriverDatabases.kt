/**
 * A database file captured byte for byte after one SQLite library wrote it, so a build linked to
 * the other library can prove it opens that file in place.
 *
 * The two iOS builds cannot share a process: the bundled SQLite and the system one export the same
 * symbols, so each build links exactly one of them (see the module's build file). Each capture was
 * made once, in its own build, by the same steps — [ShippedDatabaseFixture.writeTo] with that
 * build's driver, then the library's own database builder opening it and writing
 * [CROSS_DRIVER_MARKER_ROW], then closing it (Room had switched the file to WAL, and closing
 * checkpointed it) — and stored as the non-zero byte runs of the main database file.
 *
 * @property sizeBytes length of the file.
 * @property sqliteVersionNumber `SQLITE_VERSION_NUMBER` of the library that last wrote the file, as
 *   the file's own header records it at offset 96.
 * @property runs `offset to hex` for every stretch of the file that is not zeros.
 */
internal class CrossDriverDatabase(
    val sizeBytes: Int,
    val sqliteVersionNumber: Int,
    val runs: List<Pair<Int, String>>,
) {
    /** The file's bytes. */
    fun bytes(): ByteArray {
        val bytes = ByteArray(sizeBytes)
        runs.forEach { (offset, hex) ->
            for (index in 0 until hex.length / 2) {
                bytes[offset + index] =
                    hex.substring(index * 2, index * 2 + 2).toInt(radix = 16).toByte()
            }
        }
        return bytes
    }
}

/** The row each capture wrote through Room after opening the shipped fixture. */
internal val CROSS_DRIVER_MARKER_ROW: CachedQueryRow =
    CachedQueryRow(
        table = "todos",
        cacheKey = "todos?select=*&written_by=room",
        payload = """[{"id":3,"title":"Written through Room"}]""",
        updatedAt = 1_727_000_000_200,
    )

/**
 * What a cross-driver capture reads back as: the shipped fixture plus [CROSS_DRIVER_MARKER_ROW].
 */
internal val CROSS_DRIVER_CONTENTS: OfflineDatabaseContents =
    SHIPPED_FIXTURE_CONTENTS.copy(
        cachedQueryRows =
            (SHIPPED_FIXTURE_CONTENTS.cachedQueryRows + CROSS_DRIVER_MARKER_ROW).sortedBy {
                it.updatedAt
            }
    )

