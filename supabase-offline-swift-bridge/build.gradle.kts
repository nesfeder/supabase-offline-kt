import org.jetbrains.kotlin.gradle.plugin.mpp.Framework
import org.jetbrains.kotlin.gradle.plugin.mpp.KotlinNativeTarget
import org.jetbrains.kotlin.gradle.plugin.mpp.apple.XCFramework
import org.jetbrains.kotlin.gradle.plugin.mpp.apple.XCFrameworkTask
import org.jetbrains.kotlin.gradle.tasks.KotlinNativeLink

// The Kotlin side of the Swift package: the framework SupabaseOfflineCore, whose Objective-C header
// is the only Kotlin surface a Swift target can reach. iOS targets only; never published, so it
// carries no Maven identity, API record, documentation or coverage (supabase-offline.published).
plugins {
    alias(libs.plugins.kotlinMultiplatform)
    // For supabase-kt's own serializers of the Storage values a call answers with.
    alias(libs.plugins.kotlinSerialization)
    id("supabase-offline.kmp-library")
}

// The Swift package links Apple's SQLite, so its framework is built from the system-SQLite build of
// the library (supabase-offline-kt/build.gradle.kts): the same property selects the library's
// driver, and here the linker flag every binary of this module needs with it.
val iosSqlite = providers.gradleProperty("supabase.offline.iosSqlite").getOrElse("bundled")

check(iosSqlite == "bundled" || iosSqlite == "system") {
    "supabase.offline.iosSqlite must be \"bundled\" or \"system\", was \"$iosSqlite\""
}

val iosUsesSystemSqlite = iosSqlite == "system"

// The request-rendering fixture the Swift package's tests read too, compiled into the iOS tests as
// a string constant: a test binary on the simulator cannot rely on the repository's path.
val renderingFixture = layout.projectDirectory.file("fixtures/request-rendering.json")
val renderingFixtureSource = layout.buildDirectory.dir("generated/renderingFixture/kotlin")
val generateRenderingFixture =
    tasks.register("generateRenderingFixture") {
        val input = renderingFixture
        val output = renderingFixtureSource
        inputs.file(input)
        outputs.dir(output)
        doLast {
            val escaped =
                input.asFile
                    .readText()
                    .replace("\\", "\\\\")
                    .replace("\"", "\\\"")
                    .replace("$", "\\$")
                    .replace("\r", "")
                    .replace("\n", "\\n")
            val file =
                output
                    .get()
                    .file("io/github/nesfeder/supabase/offline/bridge/RenderingFixtureText.kt")
                    .asFile
            file.parentFile.mkdirs()
            file.writeText(
                """
                |// Generated by supabase-offline-swift-bridge/build.gradle.kts from
                |// fixtures/request-rendering.json.
                |package io.github.nesfeder.supabase.offline.bridge
                |
                |/** The request-rendering fixture, as the file holds it. */
                |internal const val RENDERING_FIXTURE_JSON: String = "$escaped"
                |"""
                    .trimMargin()
            )
        }
    }

kotlin {
    val xcFramework = XCFramework("SupabaseOfflineCore")
    targets.withType<KotlinNativeTarget>().configureEach {
        // Nothing is exported from a dependency: the header holds this module's own types, which
        // name no type of the library, supabase-kt, Ktor or okio (scripts/check-bridge-header.py).
        binaries.framework {
            baseName = "SupabaseOfflineCore"
            isStatic = true
            xcFramework.add(this)
        }
        if (iosUsesSystemSqlite) {
            binaries.all {
                linkerOpts("-lsqlite3")
                // As in the library: an ABI gap between Room's androidx.sqlite and the system
                // variant's must fail the link, not crash at run time.
                freeCompilerArgs += "-Xpartial-linkage-loglevel=ERROR"
            }
        }
    }

    sourceSets {
        iosMain.dependencies {
            implementation(projects.supabaseOfflineKt)
            // The in-memory client behind BridgeTesting, which the Swift package's testing product
            // exposes, and the mock engine its fake server answers through.
            implementation(projects.supabaseOfflineKtTesting)
            implementation(libs.ktor.client.darwin)
            implementation(libs.ktor.client.mock)
        }

        iosTest { kotlin.srcDir(generateRenderingFixture.map { renderingFixtureSource.get() }) }
    }
}

// A framework of this module goes into the Swift package, which must never carry the bundled
// SQLite: building one without the system-SQLite property fails before it links. Tests may run on
// either build; CI runs them on the system one.
val bundledSqliteRefusal: String? =
    if (iosUsesSystemSqlite) null
    else
        "The SupabaseOfflineCore framework links Apple's SQLite: build it with " +
            "-Psupabase.offline.iosSqlite=system"

tasks
    .withType<KotlinNativeLink>()
    .matching { it.binary is Framework }
    .configureEach {
        val refusal = bundledSqliteRefusal
        doFirst { if (refusal != null) throw GradleException(refusal) }
    }

tasks.withType<XCFrameworkTask>().configureEach {
    val refusal = bundledSqliteRefusal
    doFirst { if (refusal != null) throw GradleException(refusal) }
}
