// Task to build the Support XCFramework used by the iOSApp and also required for distribution.
tasks.register<Exec>("buildSupportXCFramework") {
    group = "build"
    description = "Build iOS Support Library XCFramework"

    workingDir = rootDir
    commandLine("bash", "./scripts/build-support-xcframework.sh")
}

// Ensure that the SupabaseOffline XCFramework is built before building the Support XCFramework
tasks.named("assembleSupabaseOfflineReleaseXCFramework").configure {
    finalizedBy("buildSupportXCFramework")
}

group = "io.github.nesfeder.supabase-offline-kt"
version = "1.0.0"

val githubProps = runCatching {
    Properties().apply {
        load(rootProject.file("github.properties").inputStream())
    }
}.onFailure {
    println("Warning: Could not load github.properties for publishing: ${it.message}. " +
            "Make sure to place the file in the root project directory with 'username' and 'token' properties.")
}.getOrNull()

if (githubProps != null) {
    publishing {
        repositories {
            maven {
                url = uri("https://maven.pkg.github.com/nesfeder/supabase-offline-kt")
                credentials {
                    username = githubProps.getProperty("username")
                    password = githubProps.getProperty("token")
                }
            }
        }
    }
}